const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=readFileSync(new URL('../../index.html',`file://${__filename}`),'utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const elements=new Map();
const context=vm.createContext({
  window:{}, location:{hash:'#patient'}, structuredClone, setTimeout:()=>{},
  document:{addEventListener(){}, getElementById(id){if(!elements.has(id))elements.set(id,{innerHTML:''});return elements.get(id);}}
});
vm.runInContext(source,context);
const app=context.window;
const markup=id=>elements.get(id)?.innerHTML||'';
app.onload();
app.openAppointmentPass('p1',0);
assert.match(markup('modal-root'),/Appointment Pass/);
assert.match(markup('modal-root'),/Cardiology Follow-up/);
assert.match(markup('modal-root'),/10:30 AM/);
app.closeModal();
app.openBookAppointmentModal();
app.setApptSlot('02:15 PM');
assert.match(markup('modal-root'),/slot btn selected" aria-pressed="true" onclick="setApptSlot\('02:15 PM'\)/);
assert.doesNotMatch(markup('modal-root'),/slot btn selected" aria-pressed="true" onclick="setApptSlot\('10:30 AM'\)/);
app.setApptDoc('Dr. Marko Zupan');
assert.match(markup('modal-root'),/choice selected" aria-pressed="true" onclick="setApptDoc\('Dr. Marko Zupan'\)/);
app.confirmAppointment();
app.openAppointmentPass('p1',2);
assert.match(markup('modal-root'),/02:15 PM/);
assert.match(markup('modal-root'),/Dr. Marko Zupan/);
app.closeModal();
app.switchRole('doctor');
const queueIds=()=>[...markup('app').matchAll(/onclick="selectDocPatient\('([^']+)'\)/g)].map(m=>m[1]);
app.setDocFilter('urgent');
assert.deepEqual(queueIds(),['p2']);
app.setDocFilter('questionnaires');
assert.deepEqual(queueIds(),['p1']);
app.setDocFilter('all');
assert.deepEqual(queueIds(),['p1','p2','p3']);
app.selectDocPatient('p1');
app.approveCarePlan();
assert.deepEqual(queueIds(),['p2','p3','p1']);
assert.match(markup('app'),/queue-row btn approved selected/);
assert.match(markup('app'),/2 Pending/);
assert.match(markup('app'),/onclick="approveCarePlan\(\)" disabled/);
app.approveCarePlan();
assert.match(markup('app'),/2 Pending/);
app.selectDocPatient('p2');
app.approveCarePlan();
assert.deepEqual(queueIds(),['p3','p1','p2']);
app.setDocFilter('urgent');
assert.deepEqual(queueIds(),['p2']);
assert.match(markup('app'),/Care Plan Approved/);
app.resetDemoState();
assert.deepEqual(queueIds(),['p1','p2','p3']);
assert.match(markup('app'),/3 Pending/);
for(const role of ['patient','doctor','nurse'])assert.match(readFileSync(new URL(`../../${role}.html`,`file://${__filename}`),'utf8'),new RegExp(`index.html#${role}`));
console.log('Passed: appointment passes, booking selection and confirmation, queue filters, approval ordering/status/idempotency, reset, and renamed page links.');

app.selectDocPatient('p1');
app.switchRole('patient');
app.openRenewalRequestModal();
assert.match(markup('modal-root'),/Lisinopril 10mg/);
assert.match(markup('modal-root'),/onclick="submitRenewalRequest\(\)" disabled/);
elements.get('renewal-notes') || context.document.getElementById('renewal-notes');
elements.get('renewal-notes').value='<b>Please review</b>';
app.toggleRenewalMedication(0);
assert.match(markup('modal-root'),/choice selected/);
assert.match(markup('modal-root'),/&lt;b&gt;Please review&lt;\/b&gt;/);
app.toggleRenewalMedication(1);
app.submitRenewalRequest();
app.setPatientTab('requests');
assert.match(markup('app'),/Medication renewal: Lisinopril 10mg, Salbutamol Inhaler/);
app.openRenewalRequestModal();
assert.match(markup('modal-root'),/onclick="toggleRenewalMedication\(0\)" disabled/);
app.toggleRenewalMedication(0);
assert.match(markup('modal-root'),/onclick="submitRenewalRequest\(\)" disabled/);
app.closeModal();
app.switchRole('doctor');
assert.match(markup('app'),/Lisinopril 10mg · 1 tablet daily; Salbutamol Inhaler/);
assert.match(markup('app'),/&lt;b&gt;Please review&lt;\/b&gt;/);
app.selectDocPatient('p2');
app.openRenewalRequestModal();
assert.match(markup('modal-root'),/Metformin 850mg/);
assert.doesNotMatch(markup('modal-root'),/Lisinopril/);
console.log('Passed: medication selection, notes escaping, pending requests, duplicate prevention, doctor visibility, and patient isolation.');
app.closeModal();
app.selectDocPatient('p1');
assert.match(markup('app'),/Medication renewal requested/);
assert.match(markup('app'),/Review the requested medications for prescription renewal/);
assert.match(markup('app'),/Urine sample requested/);
assert.doesNotMatch(markup('app'),/About this Prototype/);
app.switchRole('nurse');
app.selectNursePatient('np1');
assert.match(markup('app'),/Medication renewal is awaiting doctor review/);
assert.match(markup('app'),/Lisinopril 10mg/);
app.selectNursePatient('np2');
assert.doesNotMatch(markup('app'),/Medication renewal is awaiting doctor review/);
assert.doesNotMatch(markup('app'),/About this Prototype/);
console.log('Passed: distinct doctor/nurse request messages, patient-specific details, and removed About button.');
